"""Golden DOT and SVG files for the §7.5, §7.6 and a Thompson machine.

Regenerate with `UPDATE_GOLDEN=1 pytest tests/unit/test_golden.py` after a deliberate
change, and review the diff. DOT is ours, so it must match byte for byte. SVG geometry
depends on the Graphviz version and the installed fonts, so the exact comparison runs
only when both match the golden file; the structure (every element, id, class,
title, label and tooltip, in order) is compared everywhere, CI included.
"""

import os
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

import pytest

from nfa_studio.compile import compile
from nfa_studio.core.model import Automaton
from nfa_studio.ir.normalize import validate_ir
from nfa_studio.render.dot import dot_source
from nfa_studio.render.json_graph import diagram_graph
from nfa_studio.render.svg import render_diagram

GOLDEN = Path(__file__).resolve().parents[1] / "golden"
UPDATE = os.environ.get("UPDATE_GOLDEN") == "1"
XLINK_TITLE = "{http://www.w3.org/1999/xlink}title"

MACHINES: dict[str, dict[str, Any]] = {
    # spec §7.5
    "ends_with_ab": {"type": "ends_with", "pattern": "ab"},
    # spec §7.6
    "not_containing_aa": {"type": "avoids", "pattern": "aa"},
    "regex_ab_star": {"type": "regex", "expr": "(ab)*"},
}


def machine(name: str) -> Automaton:
    doc = validate_ir(
        {"alphabet": {"symbols": ["a", "b"], "source": "user"}, "language": MACHINES[name]}
    )
    return compile(doc).automaton


def check_golden(path: Path, actual: str) -> str:
    if UPDATE:
        path.write_text(actual, encoding="utf-8", newline="\n")
    return path.read_text(encoding="utf-8")


def without_version(svg: str) -> str:
    return re.sub(
        r"<!-- Generated by graphviz version .*?-->", "<!-- Graphviz -->", svg, flags=re.S
    )


def engine(svg: str) -> tuple[str, frozenset[str]]:
    """The Graphviz version and fonts that produced `svg`; equal engines give equal bytes."""
    version = re.search(r"Generated by graphviz version (\S+)", svg)
    fonts = frozenset(re.findall(r'font-family="([^"]*)"', svg))
    return (version[1] if version else "", fonts)


def structure(svg: str) -> list[tuple[str, ...]]:
    """Every element in order with its id, class, text and tooltip, but no geometry."""
    shape: list[tuple[str, ...]] = []
    for element in ET.fromstring(svg.encode("utf-8")).iter():
        tag = element.tag.rsplit("}", 1)[-1]
        shape.append(
            (
                tag,
                element.get("id", ""),
                element.get("class", ""),
                (element.text or "").strip(),
                element.get(XLINK_TITLE, ""),
                "dashed" if element.get("stroke-dasharray") else "",
            )
        )
    return shape


@pytest.mark.parametrize("name", MACHINES)
def test_golden_dot(name: str) -> None:
    actual = dot_source(diagram_graph(machine(name)))
    assert actual == check_golden(GOLDEN / f"{name}.dot", actual)


@pytest.mark.parametrize("name", MACHINES)
def test_golden_svg(name: str) -> None:
    actual = render_diagram(machine(name)).content.decode("utf-8")
    golden = check_golden(GOLDEN / f"{name}.svg", actual)
    assert structure(actual) == structure(golden)
    if engine(actual) == engine(golden):
        assert without_version(actual) == without_version(golden)
